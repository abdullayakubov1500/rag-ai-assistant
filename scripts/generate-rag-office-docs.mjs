const ragDir = path.join(process.cwd(), 'docs', 'rag');

function mdToDocxParagraphs(markdownText) {
  const lines = markdownText.split(/\r?\n/);
  const paragraphs = [];

  for (const rawLine of lines) {
    const line = rawLine.trim();
    if (!line || line === '---') continue;

    if (line.startsWith('# ')) {
      paragraphs.push(
        new Paragraph({
          text: line.replace(/^#\s+/, ''),
          heading: HeadingLevel.HEADING_1,
          spacing: { before: 240, after: 120 },
        })
      );
    } else if (line.startsWith('## ')) {
      paragraphs.push(
        new Paragraph({
          text: line.replace(/^##\s+/, ''),
          heading: HeadingLevel.HEADING_2,
          spacing: { before: 200, after: 100 },
        })
      );
    } else if (line.startsWith('### ')) {
      paragraphs.push(
        new Paragraph({
          text: line.replace(/^###\s+/, ''),
          heading: HeadingLevel.HEADING_3,
          spacing: { before: 160, after: 80 },
        })
      );
    } else if (line.startsWith('|')) {
      // Skip markdown table separator rows
      if (/^\|[\s\-|:]+\|$/.test(line)) continue;
      const cells = line
        .split('|')
        .slice(1, -1)
        .map((c) => c.replace(/\*\*/g, '').trim());
      paragraphs.push(
        new Paragraph({
          children: [new TextRun({ text: cells.join(' | ') })],
          spacing: { after: 60 },
        })
      );
    } else {
      const cleanText = line.replace(/\*\*/g, '');
      paragraphs.push(
        new Paragraph({
          children: [new TextRun({ text: cleanText })],
          spacing: { after: 80 },
        })
      );
    }
  }

  return paragraphs;
}

async function generateDocxFromMd(mdFilename, docxFilename) {
  const mdPath = path.join(ragDir, mdFilename);
  const docxPath = path.join(ragDir, docxFilename);
  const mdText = fs.readFileSync(mdPath, 'utf-8');

  const doc = new Document({
    sections: [
      {
        properties: {},
        children: mdToDocxParagraphs(mdText),
      },
    ],
  });

  const buffer = await Packer.toBuffer(doc);
  fs.writeFileSync(docxPath, buffer);
  console.log(`Generated: ${docxPath}`);
}

